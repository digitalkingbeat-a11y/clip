/**
 * Helper to retrieve template by ID
 */
export function getTemplateById(id: string): ProjectTemplate | undefined {
  return PROJECT_TEMPLATES.find((t) => t.id === id);
}

/**
 * Filter templates by category and search query
 */
export function filterTemplates(
  category: string,
  aspectRatio: string,
  query: string
): ProjectTemplate[] {
  return PROJECT_TEMPLATES.filter((tpl) => {
    const matchesCategory = category === "all" || tpl.category === category;
    const matchesRatio = aspectRatio === "all" || tpl.aspectRatio === aspectRatio;
    const matchesQuery =
      !query.trim() ||
      tpl.title.toLowerCase().includes(query.toLowerCase()) ||
      tpl.industry.toLowerCase().includes(query.toLowerCase()) ||
      tpl.description.toLowerCase().includes(query.toLowerCase()) ||
      tpl.tags.some((tag) => tag.toLowerCase().includes(query.toLowerCase()));

    return matchesCategory && matchesRatio && matchesQuery;
  });
}
